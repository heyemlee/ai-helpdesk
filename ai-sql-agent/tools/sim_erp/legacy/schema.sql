-- 遗留 ERP 抽取层：金蝶 / 用友 / SAP 那一类的字段命名。
--
-- 这份 schema 存在的唯一理由，是补上 sim_erp 那份数据**没有**预演的那道坎：
-- sim_erp 的字段名是业务白话（job_no、contract_amount），跑通它证明不了
-- 能接真 ERP。真实抽取长这样——表名是 T_ 前缀 + 域缩写，字段名是 F 前缀 +
-- 缩写，状态是单字母代码，日期是 8 位整数，金额分含税不含税但名字看不出来，
-- 而且**一行注释都没有**（真库的注释要么没有，要么是十年前另一个系统的）。
--
-- 数据与 runtime_data/sim/erp.db 一一对应，同一批业务事实换一身皮：
-- 同一个问题在两边都应该问得出同一个答案。问不出来，差距就在命名这一层，
-- 而那正是语义层要填的。
PRAGMA foreign_keys = OFF;

DROP TABLE IF EXISTS T_SAL_ORDERENTRY;
DROP TABLE IF EXISTS T_AR_RECEIVABLE;
DROP TABLE IF EXISTS T_AR_RECEIVEBILL;
DROP TABLE IF EXISTS T_SAL_CHGORDER;
DROP TABLE IF EXISTS T_SAL_ORDER;
DROP TABLE IF EXISTS T_BD_CUSTOMER;

CREATE TABLE T_BD_CUSTOMER (
    FCUSTID     TEXT PRIMARY KEY,
    FNAME       TEXT NOT NULL,
    FCUSTTYPE   TEXT NOT NULL,
    FPAYCOND    TEXT NOT NULL,
    FCREDITLMT  REAL,
    FFORBIDSTS  TEXT NOT NULL
);

CREATE TABLE T_SAL_ORDER (
    FBILLNO     TEXT PRIMARY KEY,
    FCUSTID     TEXT NOT NULL,
    FSUBDIV     TEXT,
    FLOTNO      TEXT,
    FPLANNM     TEXT,
    FADDR       TEXT NOT NULL,
    FCITY       TEXT NOT NULL,
    FPROV       TEXT NOT NULL,
    FPROVSTD    TEXT NOT NULL,
    FBIZTYPE    TEXT NOT NULL,
    FAMOUNT     REAL NOT NULL,
    FDATE       INTEGER NOT NULL,
    FDELIVDATE  INTEGER,
    FDOCSTATUS  TEXT NOT NULL
);

CREATE TABLE T_SAL_ORDERENTRY (
    FENTRYID    TEXT PRIMARY KEY,
    FBILLNO     TEXT NOT NULL,
    FSEQ        INTEGER NOT NULL,
    FMATCAT     TEXT NOT NULL,
    FMATNO      TEXT NOT NULL,
    FMATNAME    TEXT NOT NULL,
    FQTY        INTEGER NOT NULL,
    FPRICE      REAL NOT NULL,
    FAMOUNT     REAL NOT NULL
);

CREATE TABLE T_SAL_CHGORDER (
    FCHGNO      TEXT PRIMARY KEY,
    FBILLNO     TEXT NOT NULL,
    FCHGRSN     TEXT NOT NULL,
    FCHGAMT     REAL NOT NULL,
    FAPPLYDATE  INTEGER NOT NULL,
    FAUDITDATE  INTEGER,
    FDOCSTATUS  TEXT NOT NULL
);

CREATE TABLE T_AR_RECEIVABLE (
    FARNO       TEXT PRIMARY KEY,
    FBILLNO     TEXT NOT NULL,
    FARTYPE     TEXT NOT NULL,
    FBILLDATE   INTEGER NOT NULL,
    FAMOUNT     REAL NOT NULL,
    FDUEDATE    INTEGER NOT NULL,
    FSETTLESTS  TEXT NOT NULL
);

CREATE TABLE T_AR_RECEIVEBILL (
    FRECNO      TEXT PRIMARY KEY,
    FARNO       TEXT NOT NULL,
    FAMOUNT     REAL NOT NULL,
    FRECDATE    INTEGER NOT NULL,
    FSETTLETYPE TEXT NOT NULL
);

CREATE INDEX IDX_ORD_CUST ON T_SAL_ORDER(FCUSTID);
CREATE INDEX IDX_ENT_BILL ON T_SAL_ORDERENTRY(FBILLNO);
CREATE INDEX IDX_AR_BILL   ON T_AR_RECEIVABLE(FBILLNO);
CREATE INDEX IDX_REC_AR    ON T_AR_RECEIVEBILL(FARNO);
