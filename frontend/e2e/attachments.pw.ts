import { test, expect } from '@playwright/test'
import path from 'node:path'
const fixture = (name: string) => path.join(import.meta.dirname, 'fixtures', name)

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('helpdesk.lang', 'zh'))
  await page.request.post('/api/test/login')
  await page.goto('/')
})

test('chat image-only submission, continuation, reload, private preview and download', async ({ page, browser }) => {
  await page.getByLabel('关联问题').selectOption('new')
  await page.getByLabel('问题类型').selectOption('missing_parts')
  await page.locator('input[type=file]').setInputFiles(fixture('clear.png'))
  await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('已按业务记录核实，请员工确认内部草稿。', { exact: false })).toBeVisible({ timeout: 30_000 })
  const state = await (await page.request.get('/api/test/state')).json()
  const c = state.cases[0]
  expect(c.facts.quantity.value).toBe('2')
  expect(state.queries[0].user_id).toBe('ai-helpdesk')
  expect(state.queries[0].session_id).toMatch(/^hd-/) // SQL client scopes and hashes the Case session
  await page.reload()
  await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载原图' }).first().click()
  expect((await download).suggestedFilename()).toBe('clear.png')
  const detail = await (await page.request.get(`/api/tickets/${c.id}/case`)).json()
  expect(detail.runs).toHaveLength(2)
  expect(detail.drafts).toHaveLength(1)
  const stranger = await browser.newContext()
  expect((await stranger.request.get(`${process.env.BROWSER_FRONTEND_URL}/api/attachments/${detail.materials[0].attachment_id}/content`)).status()).toBe(401)
  await stranger.close()
  await page.request.post('/api/test/revoke')
  await page.getByRole('button', { name: '重试预览' }).first().click()
  await expect(page.getByText('预览不可用，请检查登录权限后重试。')).toBeVisible()
})

test('workbench retains upload retries, exposes conflict, accepts clearer supplement', async ({ page }) => {
  await page.goto('/#/tickets')
  await page.getByRole('button', { name: '进入跨消息工单' }).click()
  const work = page.getByRole('region', { name: '跨消息工单' })
  await work.getByLabel('问题类型').selectOption('missing_parts')
  await page.request.post('/api/test/fail-upload')
  await work.locator('input[type=file]').setInputFiles(fixture('conflict.png'))
  await expect(work.getByText('上传失败，文件已保留，可重试。')).toBeVisible()
  await work.getByRole('button', { name: '重试上传' }).click()
  await expect(work.getByRole('img', { name: 'conflict.png' })).toBeVisible()
  await work.getByRole('button', { name: '保存并继续' }).click()
  await expect(work.getByText('存在冲突').first()).toBeVisible({ timeout: 30_000 })
  await expect(work.getByText('图片待核实：数量', { exact: false })).toBeVisible()
  await expect(work.getByLabel('image:quantity')).toHaveCount(0)
  await work.locator('input[type=file]').setInputFiles(fixture('clear.png'))
  await expect(work.getByRole('img', { name: 'clear.png' })).toBeVisible()
  await work.getByRole('button', { name: '保存并继续' }).click()
  await expect(work.getByText('已按业务记录核实，请员工确认内部草稿。').first()).toBeVisible({ timeout: 30_000 })
  await expect(work.getByText('待补: 无')).toBeVisible()
  await work.getByRole('button', { name: '人工接管' }).click()
  await expect(work.getByRole('button', { name: '交回助手' })).toBeVisible()
  const before = await (await page.request.get('/api/test/state')).json()
  await work.getByRole('button', { name: '重新核对此图' }).last().click()
  await expect(work.getByText('此问题已由人工接管，材料已保存。').first()).toBeVisible()
  const after = await (await page.request.get('/api/test/state')).json()
  expect(after.model_calls).toBe(before.model_calls)
})

for (const phase of ['model', 'answer']) {
  test(`reload while ${phase} is running follows durable work without resubmission`, async ({ page }) => {
    const before = await (await page.request.get('/api/test/state')).json()
    await page.request.post(`/api/test/hold/${phase}`)
    await page.getByLabel('关联问题').selectOption('new')
    await page.getByLabel('问题类型').selectOption('missing_parts')
    await page.locator('input[type=file]').setInputFiles(fixture('clear.png'))
    await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await expect.poll(async () => (await (await page.request.get('/api/test/state')).json()).waiting).toBe(phase)
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('ai-helpdesk.console.settings.v2') || '{}').caseId)).toBeTruthy()
    await page.reload()
    await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
    await page.request.post(`/api/test/hold/${phase}?release=true`)
    await expect(page.getByText('已按业务记录核实，请员工确认内部草稿。', { exact: false })).toBeVisible({ timeout: 30_000 })
    const after = await (await page.request.get('/api/test/state')).json()
    expect(after.model_calls - before.model_calls).toBe(1)
    expect(after.cases.length - before.cases.length).toBe(1)
  })
}

test('switching away cancels restored Case polling without moving its reply into ordinary chat', async ({ page }) => {
  await page.request.post('/api/test/hold/model')
  await page.getByLabel('关联问题').selectOption('new')
  await page.getByLabel('问题类型').selectOption('missing_parts')
  await page.locator('input[type=file]').setInputFiles(fixture('clear.png'))
  await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect.poll(async () => (await (await page.request.get('/api/test/state')).json()).waiting).toBe('model')
  const caseId = await page.evaluate(() => JSON.parse(localStorage.getItem('ai-helpdesk.console.settings.v2') || '{}').caseId)
  await page.reload()
  await expect(page.getByRole('img', { name: 'clear.png' })).toBeVisible()
  await page.getByLabel('关联问题').selectOption('')
  await page.request.post('/api/test/hold/model?release=true')
  await expect.poll(async () => {
    const c = await (await page.request.get(`/api/tickets/${caseId}/case`)).json()
    return c.drafts.length
  }).toBe(1)
  await expect(page.getByText('已按业务记录核实，请员工确认内部草稿。')).toHaveCount(0)
  await expect(page.getByRole('img', { name: 'clear.png' })).toHaveCount(0)
})
