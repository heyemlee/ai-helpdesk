"""A metadata clock denotes its exact instant and its own semantic role."""
import pytest
from test_policy_metadata_dates import check

TIMES = {"policy_as_of": ["2036-05-03T10:11:12Z"],
         "policy_effective_at": ["2036-05-03T10:11:11Z"],
         "policy_expires_at": ["2036-05-04T10:00:00Z"]}


@pytest.mark.parametrize("text", [
    "有效性判定时点：2036-05-03 10:11:12 UTC",
    "有效性判定时点：2036-05-03T10:11:12Z",
    "有效性判定时点：2036-05-03T10:11:12+00:00",
    "有效性判定时点：2036-05-03T12:11:12+02:00",
    "有效性判定时点：2036-05-02T23:11:12-11:00",
    "该版本自2036-05-03T12:11:11+02:00生效。",
    "失效时点：2036-05-04T06:00:00-04:00",
    "> 截至2036-05-03T12:11:12+02:00，本次检索，未找到可引用的已发布档案归集政策。",
])
def test_equivalent_aware_instants_preserve_metadata_role(text):
    check(text, TIMES, blocked=False)


@pytest.mark.parametrize("text", [
    "有效性判定时点：2036-05-03T11:11:12Z",
    "有效性判定时点：2036-05-03T10:12:12Z",
    "有效性判定时点：2036-05-03T10:11:13Z",
    "有效性判定时点：2036-05-03T10:11:11Z",
    "该版本自2036-05-03T10:11:12Z生效。",
    "有效性判定时点：2036-05-03T10:11:12+01:00",
    "有效性判定时点：2036-05-03T10:11:12-01:00",
    "有效性判定时点：2036-05-03T10:11:12 UTC+01:00",
    "有效性判定时点：2036-05-03T10:11:12+24:00",
    "有效性判定时点：2036-05-03T10:11:12+00:60",
    "有效性判定时点：2036-05-03T10:11:12Zjunk",
    "该版本自2036-05-03T10:11:11+01:00生效。",
    "失效时点：2036-05-04T10:00:00+01:00",
    "截至2036-05-03T10:11:12+01:00，本次检索，未找到可引用的已发布档案归集政策。",
    "有效性判定时点：2036-05-03T10:11:12Z，届时赔付。",
    "有效性判定时点：2036-05-03T10:11:12Z；保证2036-05-03T10:11:12Z送达。",
    "该版本自2036-05-03T10:11:11Z生效，并于同一天付款。",
    "保证2036-05-03T10:11:12Z送达。",
    "保证2036-05-03T12:11:12+02:00付款。",
])
def test_other_instants_roles_and_business_values_do_not_borrow_metadata(text):
    check(text, TIMES, blocked=True)
